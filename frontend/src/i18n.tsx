interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (copy: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function readLocale(): Locale {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ru";
  } catch {
    return "ru";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const setLocale = (next: Locale) => {
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* Keep the language for this session. */ }
    setLocaleState(next);
    document.documentElement.lang = next;
  };
  const value = useMemo<LanguageContextValue>(() => ({
    locale,
    setLocale,
    t: (copy) => locale === "en" ? (en[copy as keyof typeof en] ?? copy) : copy,
  }), [locale]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (value) return value;
  const locale = readLocale();
  return { locale, setLocale: () => undefined, t: (copy: string) => translate(locale, copy) };
}

export function translate(locale: Locale, copy: string): string {
  return locale === "en" ? (en[copy as keyof typeof en] ?? copy) : copy;
}
